// ============================================================
// 構造体
// ============================================================
struct Player {
	float x, y, size, vy;
	int hp;
	int invincible;
	int score;
	int coins;
	int bigCoins;
};

struct Bullet {
	float x, y;
	float vx, vy;
	float radius;
	bool isActive;
};

struct Obstacle {
	float x, y, w, h;
	int type;  // ObstacleType
	int phase; // 出現/消滅ブロックの位相(0:出現から開始 / 1:消滅から開始)
	bool isActive;
};

struct Enemy {
	float x, baseY, y;
	float size;
	int hp;
	int maxHp;
	int shotTimer;
	int frame;
	int type;       // EnemyType
	int state;      // T: 0=待機 1=突撃中 / S: 0=攻撃中 1=退場中
	int shotsLeft;  // S: 残りの発射回数
	float vx, vy;   // T: 突撃中の速度(画面基準)
	bool isActive;
};

struct Coin {
	float x, y, radius;
	bool isActive;
};

struct Goal {
	float x;
	bool isActive;
};

struct Boss {
	float x, y;
	float baseY;
	float wave;
	int hp, maxHp;
	int frame;
	int aimTimer;
	int fanTimer;
	int hitFlash;
	bool isArrived;
	bool isActive;
};

struct Cannon {
	float x, y;   // 左上
	int dir;      // CannonDir
	int timer;
	bool isActive;
};

struct Barrel {
	float cx, cy;          // 中心
	float minCY, maxCY;    // 往復するY座標の範囲(中心基準)
	float dir;             // +1:下へ / -1:上へ
	bool isActive;
};

struct Sprite {
	int handle = -1;
	int w = 0;
	int h = 0;
	bool IsValid() const { return handle >= 0 && w > 0 && h > 0; }
};

