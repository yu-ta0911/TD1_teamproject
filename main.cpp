void DrawHitboxes() {
	if (!debug) return;

	bool solidNow = isDashing || (playerState == kPlayerLaunching);

	for (int i = 0; i < kMaxObstacles; i++) {
		const Obstacle& o = obstacles[i];
		if (!o.isActive) continue;
		if (!IsOnScreenX(o.x, o.w)) continue;

		unsigned int color = kDebugBlockSolid;
		switch (o.type) {
		case kObstacleBreakable:
			color = kDebugBlockNormal;
			break;
		case kObstacleGhost:
			if (!solidNow) continue; // すり抜けられる間は当たり判定なし
			break;
		case kObstacleBlink:
			if (!IsBlinkVisible(o)) continue;
			break;
		default:
			break;
		}
		DebugBox(o.x, o.y, o.w - 1.0f, o.h - 1.0f, color);
	}

	for (int i = 0; i < kMaxCannons; i++) {
		const Cannon& c = cannons[i];
		if (!c.isActive || !IsOnScreenX(c.x, kGridSize)) continue;
		DebugBox(c.x, c.y, kGridSize - 1.0f, kGridSize - 1.0f, kDebugBlockSolid);
	}

	for (int i = 0; i < kMaxBarrels; i++) {
		const Barrel& b = barrels[i];
		if (!b.isActive || !IsOnScreenX(b.cx - kBarrelSize * 0.5f, kBarrelSize)) continue;
		DebugBox(b.cx - kBarrelSize * 0.5f, b.cy - kBarrelSize * 0.5f, kBarrelSize, kBarrelSize, kDebugItem);
	}

	if (goal.isActive && IsOnScreenX(goal.x, static_cast<float>(kGoalWidth))) {
		DebugBox(goal.x, 0.0f, static_cast<float>(kGoalWidth), static_cast<float>(kScreenH), kDebugGoal);
	}

	for (int i = 0; i < kMaxCoins; i++) {
		if (coins[i].isActive && IsOnScreenX(coins[i].x - coins[i].radius, coins[i].radius * 2.0f)) {
			DebugCircle(coins[i].x, coins[i].y, coins[i].radius, kDebugItem);
		}
	}
	for (int i = 0; i < kMaxBigCoins; i++) {
		if (bigCoins[i].isActive && IsOnScreenX(bigCoins[i].x - bigCoins[i].radius, bigCoins[i].radius * 2.0f)) {
			DebugCircle(bigCoins[i].x, bigCoins[i].y, bigCoins[i].radius, kDebugItem);
		}
	}
	for (int i = 0; i < kMaxHeals; i++) {
		if (heals[i].isActive && IsOnScreenX(heals[i].x - heals[i].radius, heals[i].radius * 2.0f)) {
			DebugCircle(heals[i].x, heals[i].y, heals[i].radius, kDebugItem);
		}
	}

	for (int i = 0; i < kMaxEnemies; i++) {
		const Enemy& e = enemies[i];
		if (!e.isActive || !IsOnScreenX(e.x, e.size)) continue;
		if (e.type == kEnemyBurst && e.state == 1) continue;
		DebugBox(e.x, e.y, e.size, e.size, kDebugEnemy);
	}
	if (boss.isActive) {
		DebugBox(boss.x, boss.y, kBossW, kBossH, kDebugBoss);
	}

	for (int i = 0; i < kMaxBullets; i++) {
		if (enemyBullets[i].isActive) DebugCircle(enemyBullets[i].x, enemyBullets[i].y, enemyBullets[i].radius, kDebugEnemyBullet);
	}

	if (!isGameOver) {
		DebugBox(player.x, player.y, player.size, player.size, kDebugPlayer);
	}
}

