int CountMapSymbol(int stage, char symbol) {
	int n = 0;
	const StageInfo& s = kStages[stage];
	for (int r = 0; r < kGridRows; r++) {
		int len = RowLength(s, r);
		for (int c = 0; c < len; c++) {
			if (s.map[r][c] == symbol) n++;
		}
	}
	return n;
}

