// 描画処理:各オブジェクト
// ============================================================
void DrawObstacle(const Obstacle& o) {
	int x = static_cast<int>(o.x);
	int y = static_cast<int>(o.y);
	int w = static_cast<int>(o.w);
	int h = static_cast<int>(o.h);

	switch (o.type) {
	case kObstacleBreakable:
		DrawSpriteFit(sprBlockB, x, y, w, h, kColorBrown);
		break;
	case kObstacleSolid:
		DrawSpriteFit(sprBlockA, x, y, w, h, kColorGray);
		break;
	case kObstacleGhost: {
		// すり抜けられる間は半透明、ダッシュ中は不透明(=壁)
		bool solidNow = isDashing || (playerState == kPlayerLaunching);
		DrawVariant(sprBlockGhost, sprBlockA, x, y, w, h, kTintGhost, kColorCyan, solidNow ? 255 : 90);
		break;
	}
	case kObstacleBlink: {
		int t = BlinkTime(o);
		bool visible = (t < kBlinkFrames);
		int alpha = visible ? 255 : 40; // 消えている間も薄く見せて、タイミングを読めるようにする
		if (visible) {
			int remain = kBlinkFrames - t;
			if (remain <= kBlinkWarnFrames && (remain / 3) % 2 == 0) alpha = 110; // 消える直前は点滅
		}
		DrawVariant(sprBlockBlink, sprBlockB, x, y, w, h, kTintBlink, kColorPink, alpha);
		break;
	}
	default:
		break;
	}
}

void DrawCannon(const Cannon& c) {
	int x = static_cast<int>(c.x);
	int y = static_cast<int>(c.y);
	int s = static_cast<int>(kGridSize);
	DrawVariant(sprCannon, sprBlockA, x, y, s, s, kTintCannon, kColorDarkRed);

	// 砲口の向きが分かる黄色い印
	switch (c.dir) {
	case kCannonLeft: Novice::DrawBox(x - 6, y + 14, 12, 12, 0.0f, kColorYellow, kFillModeSolid); break;
	case kCannonUp:   Novice::DrawBox(x + 14, y - 6, 12, 12, 0.0f, kColorYellow, kFillModeSolid); break;
	case kCannonDown: Novice::DrawBox(x + 14, y + s - 6, 12, 12, 0.0f, kColorYellow, kFillModeSolid); break;
	default: break;
	}
}

void DrawEnemy(const Enemy& e) {
	// S: 退場中は点滅
	if (e.type == kEnemyBurst && e.state == 1 && (e.frame / 3) % 2 == 0) return;

	int x = static_cast<int>(e.x);
	int y = static_cast<int>(e.y);
	int s = static_cast<int>(e.size);

	switch (e.type) {
	case kEnemySway:
		DrawVariant(sprEnemySway, sprEnemyA, x, y, s, s, kTintSway, kColorBlue);
		break;
	case kEnemyCharger:
		DrawVariant(sprEnemyCharger, sprEnemyB, x, y, s, s, kTintCharger, kColorOrange);
		break;
	case kEnemyBurst:
		DrawVariant(sprEnemyBurst, sprEnemyA, x, y, s, s, kTintBurst, kColorPurple);
		break;
	default:
		DrawSpriteFit(sprEnemyA, x, y, s, s, RED);
		break;
	}
	DrawHpBar(x, y - 10, s, 5, e.hp, e.maxHp, kColorHpBar);
}

