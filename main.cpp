void AddObstacle(float x, float y, int type, int phase) {
	for (int i = 0; i < kMaxObstacles; i++) {
		if (obstacles[i].isActive) continue;
		Obstacle& o = obstacles[i];
		o.x = x;
		o.y = y;
		o.w = kGridSize;
		o.h = kGridSize;
		o.type = type;
		o.phase = phase;
		o.isActive = true;
		return;
	}
}

void AddEnemy(float x, float y, int type) {
	for (int i = 0; i < kMaxEnemies; i++) {
		if (enemies[i].isActive) continue;
		Enemy& e = enemies[i];
		e.x = x;
		e.baseY = y;
		e.y = y;
		e.size = 40.0f;
		e.hp = 3;
		e.maxHp = 3;
		e.shotTimer = 60;
		e.frame = 0;
		e.type = type;
		e.state = 0;
		e.shotsLeft = kShooterShotCount;
		e.vx = 0.0f;
		e.vy = 0.0f;
		e.isActive = true;
		return;
	}
}

void AddCannon(float x, float y, int dir, int col) {
	for (int i = 0; i < kMaxCannons; i++) {
		if (cannons[i].isActive) continue;
		Cannon& c = cannons[i];
		c.x = x;
		c.y = y;
		c.dir = dir;
		c.timer = kCannonInterval / 2 + (col * 17) % 50; // 列ごとに少しずらして一斉に撃たないようにする
		c.isActive = true;
		return;
	}
}

void AddBarrel(float x, float y) {
	for (int i = 0; i < kMaxBarrels; i++) {
		if (barrels[i].isActive) continue;
		Barrel& b = barrels[i];
		float half = kBarrelSize * 0.5f;
		float cy = y + kGridSize * 0.5f;
		b.cx = x + kGridSize * 0.5f;
		b.cy = cy;
		b.minCY = cy - kBarrelRange;
		if (b.minCY < half) b.minCY = half;
		b.maxCY = cy + kBarrelRange;
		if (b.maxCY > kScreenH - half) b.maxCY = kScreenH - half;
		b.dir = 1.0f;
		b.isActive = true;
		return;
	}
}

